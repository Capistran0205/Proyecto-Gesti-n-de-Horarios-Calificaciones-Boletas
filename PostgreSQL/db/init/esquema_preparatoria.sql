-- =====================================================================
-- Sistema de control escolar - Prep. Antonio María de Rivera
-- Esquema PostgreSQL generado a partir de DiagramaRelacionalActualizado
-- (con Area -> Especialidad y la nueva entidad AreaDisciplinar)
-- =====================================================================
-- Convenciones:
--   * Palabras clave en MAYÚSCULAS, nombres en snake_case.
--   * Catálogos pequeños con CHECK numérico (rol, estado, tipo, grado).
--   * Sin borrado físico: la baja es lógica (usuario.estado / materia.estado),
--     por eso las FK usan el comportamiento por defecto (NO ACTION).
--   * PostgreSQL NO indexa las FK automáticamente: los índices van al final.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Función genérica para mantener fecha_modificacion al día
-- Por qué: evita depender de que la aplicación la actualice en cada UPDATE.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_fecha_modificacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_modificacion := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =====================================================================
-- 1. USUARIOS Y SUS SUBTIPOS
-- =====================================================================

CREATE TABLE usuario (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(60)  NOT NULL,
    apellido_pat          VARCHAR(60)  NOT NULL,
    apellido_mat          VARCHAR(60),
    -- 0: SuperUsuario, 1: Administrador, 2: Docente, 3: Alumno
    rol                   SMALLINT     NOT NULL CHECK (rol BETWEEN 0 AND 3),
    -- Número de empleado (docentes/administradores) o matrícula (alumnos).
    -- Una cuenta por rol: si un docente también es administrador, la escuela
    -- le da otro identificador y registra otro correo (RN-GEN-09).
    usuario               VARCHAR(30)  NOT NULL UNIQUE,
    correo_electronico    VARCHAR(120) NOT NULL UNIQUE,
    contrasena            VARCHAR(255) NOT NULL,          -- hash, nunca texto plano
    -- 1: Activo, 0: Baja lógica
    estado                SMALLINT     NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
    cambio_contrasena_ini BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro        TIMESTAMP    NOT NULL DEFAULT NOW(),
    fecha_modificacion    TIMESTAMP    NOT NULL DEFAULT NOW()
);

-- Por qué: el SuperUsuario es único; este índice parcial impide un segundo.
CREATE UNIQUE INDEX uq_usuario_un_superusuario ON usuario (rol) WHERE rol = 0;

CREATE TABLE super_usuario (
    id_super_usuario INTEGER PRIMARY KEY REFERENCES usuario (id)
);

CREATE TABLE administrador (
    id_admin INTEGER  PRIMARY KEY REFERENCES usuario (id),
    curp     CHAR(18) NOT NULL UNIQUE
             CHECK (curp ~ '^[A-Z]{4}[0-9]{6}[HM][A-Z]{5}[0-9A-Z][0-9]$'),
    rfc      CHAR(13) NOT NULL UNIQUE
             CHECK (rfc ~ '^[A-ZÑ&]{4}[0-9]{6}[A-Z0-9]{3}$')
);

-- =====================================================================
-- 2. CATÁLOGOS
-- =====================================================================

-- Antes "Area": área propedéutica que el alumno cursa desde 5.º semestre
CREATE TABLE especialidad (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(80) NOT NULL UNIQUE,
    fecha_registro TIMESTAMP   NOT NULL DEFAULT NOW()
);

-- Área a la que pertenece cada materia (Ciencias Naturales, Pensamiento
-- Matemático, Inglés, ...). De aquí se derivan las áreas del docente.
CREATE TABLE area_disciplinar (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(80) NOT NULL UNIQUE,
    fecha_registro TIMESTAMP   NOT NULL DEFAULT NOW()
);

CREATE TABLE periodo_escolar (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(40) NOT NULL UNIQUE,           -- p. ej. 'Enero 2026 - Junio 2026'
    fecha_inicio DATE        NOT NULL,
    fecha_fin    DATE        NOT NULL,
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE salon (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(40) NOT NULL,
    edificio       VARCHAR(20) NOT NULL,
    -- 1: Aula normal, 2: Aula especial (laboratorio, taller, cómputo...)
    tipo           SMALLINT    NOT NULL DEFAULT 1 CHECK (tipo IN (1, 2)),
    fecha_registro TIMESTAMP   NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_salon_edificio UNIQUE (edificio, descripcion)
);

-- =====================================================================
-- 3. DOCENTE
-- =====================================================================

CREATE TABLE docente (
    id_docente          INTEGER  PRIMARY KEY REFERENCES usuario (id),
    -- Área disciplinar principal; obligatoria (así está en el mockup de
    -- registro y modificación). Sus demás áreas salen de docente_materia -> materia.
    id_area_disciplinar INTEGER  NOT NULL REFERENCES area_disciplinar (id),
    curp                CHAR(18) NOT NULL UNIQUE
                        CHECK (curp ~ '^[A-Z]{4}[0-9]{6}[HM][A-Z]{5}[0-9A-Z][0-9]$'),
    rfc                 CHAR(13) NOT NULL UNIQUE
                        CHECK (rfc ~ '^[A-ZÑ&]{4}[0-9]{6}[A-Z0-9]{3}$'),
    -- Ocupación capturada por el administrador a partir del formato externo
    disponibilidad      JSONB,
    -- Plaza mínima de 2 h, tiempo completo 40 h
    horas_plaza         SMALLINT NOT NULL CHECK (horas_plaza BETWEEN 2 AND 40)
);

CREATE TABLE docente_estudio (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_docente    INTEGER      NOT NULL REFERENCES docente (id_docente),
    descripcion   VARCHAR(120) NOT NULL,                 -- p. ej. 'Derecho'
    -- 1: TSU, 2: Licenciatura, 3: Especialidad, 4: Maestría, 5: Doctorado
    grado_estudio SMALLINT     NOT NULL CHECK (grado_estudio BETWEEN 1 AND 5)
);

-- =====================================================================
-- 4. ALUMNO
-- =====================================================================

CREATE TABLE alumno (
    id_alumno       INTEGER  PRIMARY KEY REFERENCES usuario (id),
    id_especialidad INTEGER  REFERENCES especialidad (id),
    curp            CHAR(18) NOT NULL UNIQUE
                    CHECK (curp ~ '^[A-Z]{4}[0-9]{6}[HM][A-Z]{5}[0-9A-Z][0-9]$'),
    nss             CHAR(11) UNIQUE CHECK (nss ~ '^[0-9]{11}$'),
    anio_ingreso    SMALLINT NOT NULL CHECK (anio_ingreso BETWEEN 2000 AND 2100),
    semestre        SMALLINT NOT NULL CHECK (semestre BETWEEN 1 AND 6),
    -- Regla: la especialidad es obligatoria en 5.º y 6.º y no existe antes
    CONSTRAINT ck_alumno_especialidad
        CHECK ((semestre >= 5) = (id_especialidad IS NOT NULL))
);

-- =====================================================================
-- 5. MATERIA Y LO QUE EL DOCENTE PUEDE IMPARTIR
-- =====================================================================

CREATE TABLE materia (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especialidad     INTEGER      REFERENCES especialidad (id),
    id_area_disciplinar INTEGER      NOT NULL REFERENCES area_disciplinar (id),
    nombre              VARCHAR(120) NOT NULL,
    clave               VARCHAR(20)  NOT NULL UNIQUE,   -- única, pero no es PK
    horas_semana        SMALLINT     NOT NULL CHECK (horas_semana BETWEEN 1 AND 10),
    -- 1: Tronco común, 2: Especialidad
    tipo                SMALLINT     NOT NULL CHECK (tipo IN (1, 2)),
    semestre            SMALLINT     NOT NULL CHECK (semestre BETWEEN 1 AND 6),
    -- 1: Activa, 0: Baja (ya no se puede asignar)
    estado              SMALLINT     NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
    fecha_registro      TIMESTAMP    NOT NULL DEFAULT NOW(),
    fecha_modificacion  TIMESTAMP    NOT NULL DEFAULT NOW(),
    -- Solo las materias de especialidad llevan especialidad
    CONSTRAINT ck_materia_tipo_especialidad
        CHECK ((tipo = 2) = (id_especialidad IS NOT NULL)),
    -- Las materias de especialidad solo existen en 5.º y 6.º
    CONSTRAINT ck_materia_especialidad_semestre
        CHECK (tipo = 1 OR semestre >= 5)
);

-- Materias que el docente PUEDE impartir según su perfil / área disciplinar.
-- Lo que realmente imparte queda en detalle_horario_grupo.
CREATE TABLE docente_materia (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_docente INTEGER NOT NULL REFERENCES docente (id_docente),
    id_materia INTEGER NOT NULL REFERENCES materia (id),
    CONSTRAINT uq_docente_materia UNIQUE (id_docente, id_materia)
);

-- =====================================================================
-- 6. GRUPOS
-- =====================================================================

CREATE TABLE grupo (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especialidad    INTEGER   REFERENCES especialidad (id),
    id_periodo         INTEGER   NOT NULL REFERENCES periodo_escolar (id),
    semestre           SMALLINT  NOT NULL CHECK (semestre BETWEEN 1 AND 6),
    letra              CHAR(1)   NOT NULL CHECK (letra ~ '^[A-Z]$'),
    -- Tope del administrador: 40; el SuperUsuario puede subirlo
    capacidad_max      SMALLINT  NOT NULL DEFAULT 40 CHECK (capacidad_max > 0),
    fecha_registro     TIMESTAMP NOT NULL DEFAULT NOW(),
    fecha_modificacion TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_grupo_periodo UNIQUE (id_periodo, semestre, letra),
    -- Los grupos de 5.º y 6.º son grupos de especialidad
    CONSTRAINT ck_grupo_especialidad
        CHECK ((semestre >= 5) = (id_especialidad IS NOT NULL))
);

-- Un alumno puede estar en varios grupos a lo largo del tiempo (1:N)
CREATE TABLE detalle_grupo (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo  INTEGER NOT NULL REFERENCES grupo (id),
    id_alumno INTEGER NOT NULL REFERENCES alumno (id_alumno),
    CONSTRAINT uq_detalle_grupo UNIQUE (id_grupo, id_alumno)
);

-- =====================================================================
-- 7. HORARIO (uno por grupo)
-- =====================================================================

CREATE TABLE horario_grupo (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo           INTEGER   NOT NULL UNIQUE REFERENCES grupo (id),  -- 1:1
    fecha_registro     TIMESTAMP NOT NULL DEFAULT NOW(),
    fecha_modificacion TIMESTAMP NOT NULL DEFAULT NOW()
);

-- RN-HOR-01 (se valida en la aplicación, no con CHECK): un docente de tiempo
-- completo tiene como máximo 3 materias DISTINTAS en el horario del periodo;
-- la misma materia en varios grupos cuenta como una sola.
CREATE TABLE detalle_horario_grupo (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_horario_grupo INTEGER  NOT NULL REFERENCES horario_grupo (id),
    id_docente       INTEGER  NOT NULL,
    id_materia       INTEGER  NOT NULL,
    id_salon         INTEGER  NOT NULL REFERENCES salon (id),
    dia_semana       SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 5), -- 1: lunes ... 5: viernes
    bloque           SMALLINT NOT NULL CHECK (bloque BETWEEN 1 AND 7),     -- 7 clases de 50 min
    -- Por qué FK compuesta: garantiza que solo se asigne una materia
    -- que el docente puede impartir (existe en docente_materia).
    CONSTRAINT fk_dhg_docente_materia
        FOREIGN KEY (id_docente, id_materia)
        REFERENCES docente_materia (id_docente, id_materia),
    -- Un grupo no puede tener dos clases en el mismo día y bloque
    CONSTRAINT uq_dhg_grupo_dia_bloque UNIQUE (id_horario_grupo, dia_semana, bloque)
);

-- =====================================================================
-- 8. CALIFICACIONES
-- =====================================================================

CREATE TABLE calificacion_alumno (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_docente         INTEGER      NOT NULL REFERENCES docente (id_docente),
    id_alumno          INTEGER      NOT NULL REFERENCES alumno (id_alumno),
    id_grupo           INTEGER      NOT NULL REFERENCES grupo (id),
    id_materia         INTEGER      NOT NULL REFERENCES materia (id),
    id_periodo         INTEGER      NOT NULL REFERENCES periodo_escolar (id),
    -- Parcial 1, 2 o 3 (no confundir con el bloque horario)
    bloque             SMALLINT     NOT NULL CHECK (bloque BETWEEN 1 AND 3),
    calificacion       NUMERIC(4,2) NOT NULL CHECK (calificacion BETWEEN 5 AND 10),
    fecha_registro     TIMESTAMP    NOT NULL DEFAULT NOW(),
    fecha_modificacion TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_calificacion UNIQUE (id_alumno, id_materia, id_periodo, bloque)
);

-- =====================================================================
-- 9. TRIGGERS DE fecha_modificacion
-- =====================================================================

CREATE TRIGGER trg_usuario_fmod             BEFORE UPDATE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion();
CREATE TRIGGER trg_materia_fmod             BEFORE UPDATE ON materia
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion();
CREATE TRIGGER trg_grupo_fmod               BEFORE UPDATE ON grupo
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion();
CREATE TRIGGER trg_horario_grupo_fmod       BEFORE UPDATE ON horario_grupo
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion();
CREATE TRIGGER trg_calificacion_alumno_fmod BEFORE UPDATE ON calificacion_alumno
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion();

-- =====================================================================
-- 10. ÍNDICES SOBRE FK
-- Rendimiento: PostgreSQL no los crea solo. Se omiten las FK que ya son
-- la primera columna de un UNIQUE o PRIMARY KEY (ya están indexadas).
-- =====================================================================

CREATE INDEX idx_docente_area_disciplinar  ON docente (id_area_disciplinar);
CREATE INDEX idx_docente_estudio_docente   ON docente_estudio (id_docente);
CREATE INDEX idx_alumno_especialidad       ON alumno (id_especialidad);
CREATE INDEX idx_materia_especialidad      ON materia (id_especialidad);
CREATE INDEX idx_materia_area_disciplinar  ON materia (id_area_disciplinar);
CREATE INDEX idx_docente_materia_materia   ON docente_materia (id_materia);
CREATE INDEX idx_grupo_especialidad        ON grupo (id_especialidad);
CREATE INDEX idx_detalle_grupo_alumno      ON detalle_grupo (id_alumno);
CREATE INDEX idx_dhg_docente_dia_bloque    ON detalle_horario_grupo (id_docente, dia_semana, bloque);
CREATE INDEX idx_dhg_salon_dia_bloque      ON detalle_horario_grupo (id_salon, dia_semana, bloque);
CREATE INDEX idx_dhg_materia               ON detalle_horario_grupo (id_materia);
CREATE INDEX idx_calif_docente             ON calificacion_alumno (id_docente);
CREATE INDEX idx_calif_grupo_materia       ON calificacion_alumno (id_grupo, id_materia);
CREATE INDEX idx_calif_periodo             ON calificacion_alumno (id_periodo);

COMMIT;
